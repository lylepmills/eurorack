void BuzzEngine::Init(BufferAllocator* allocator) {
  // No delay lines or dynamic buffers: only the const zone tables (flash)
  // and per-voice state, so the engine takes nothing from the shared 16 KiB
  // arena.
  (void) allocator;
  Reset();
}

void BuzzEngine::Reset() {
  phase0_ = 0.0f;
  phase1_ = 0.0f;
  frequency0_ = 0.01f;
  frequency1_ = 0.01f;
  zone_position0_ = 0.0f;
  zone_position1_ = 0.0f;
  osc0_decimator_ = 0.0f;
  osc1_decimator_ = 0.0f;
}

void BuzzEngine::Render(
    const EngineParameters& parameters,
    float* out,
    float* aux,
    size_t size,
    bool* already_enveloped) {
  *already_enveloped = false;

  if (parameters.trigger & TRIGGER_RISING_EDGE) {
    // Braids itself never resets BUZZ's phase (its sync input is unused by
    // this port, and MacroOscillator::Strike() only reaches the digital
    // oscillator bank, not the analog one BUZZ uses) -- this is a Plaits
    // convention for predictable note onsets, harmless to fidelity since the
    // A/B reference never triggers.
    phase0_ = 0.0f;
    phase1_ = 0.0f;
  }

  const bool stereo = PLAITS_STEREO_BUZZ && parameters.stereo;

  // TIMBRE (Braids' parameter_[0]): the harmonic-count shift shared by both
  // oscillators (analog_oscillator.cc:568). Applied to a note clamped the
  // way Braids' own pitch_ is clamped before RenderBuzz reads it
  // (analog_oscillator.cc:82-86) -- zone selection only, never the playback
  // pitch below.
  float zone_note0 = parameters.note;
  CONSTRAIN(zone_note0, 0.0f, kBuzzZoneSelectMaxNote);
  const float harmonic_shift =
      kBuzzShiftSemitones * (1.0f - parameters.timbre);

  // MACRO: widens HARMONICS' detune reach past the module's own sub-semitone
  // ceiling. The detent at noon reproduces that ceiling exactly.
  const float detune_range = ApplyMacro(
      kBuzzStockDetuneSemitones, 0.0f, kBuzzMacroMaxDetuneSemitones,
      parameters.macro);
  // HARMONICS (Braids' parameter_[1] / COLOR): the detune amount within
  // whatever range MACRO sets (analog_oscillator.cc:339's only use of
  // COLOR -- it never touches harmonic content, see the header).
  const float detune = detune_range * parameters.harmonics;

  // MORPH: the independent per-voice harmonic-content axis Braids' single
  // TIMBRE knob cannot reach. Zero at noon reproduces Braids (both voices
  // read the same zone); away from noon, voice 2's zone diverges.
  const float spread =
      (parameters.morph - 0.5f) * 2.0f * kBuzzMaxSpreadZones;

  float zone_note1 = parameters.note + detune;
  CONSTRAIN(zone_note1, 0.0f, kBuzzZoneSelectMaxNote);

  const float target_zone_position0 =
      (zone_note0 + harmonic_shift) / kBuzzZoneSemitones;
  const float target_zone_position1 =
      (zone_note1 + harmonic_shift) / kBuzzZoneSemitones + spread;

  // RATE (SPEC R5): RenderBuzz has no internal oversampling of its own, but
  // its wavetable was generated at 96 kHz (see header). The port runs both
  // oscillators' zone lookup and phase accumulation at 2x and decimates
  // through the same [0.25, 0.5, 0.25] halfband `z-filter` uses for the
  // identical situation.
  const float target_frequency0 = NoteToFrequency(parameters.note) * 0.5f;
  const float target_frequency1 =
      NoteToFrequency(parameters.note + detune) * 0.5f;

  ParameterInterpolator fm0(&frequency0_, target_frequency0, size * 2);
  ParameterInterpolator fm1(&frequency1_, target_frequency1, size * 2);
  ParameterInterpolator zone0_modulation(
      &zone_position0_, target_zone_position0, size * 2);
  ParameterInterpolator zone1_modulation(
      &zone_position1_, target_zone_position1, size * 2);

  for (size_t i = 0; i < size; ++i) {
    float osc0_sub[2];
    float osc1_sub[2];
    for (int s = 0; s < 2; ++s) {
      const float f0 = fm0.Next();
      const float f1 = fm1.Next();
      const float zp0 = zone0_modulation.Next();
      const float zp1 = zone1_modulation.Next();

      phase0_ += f0;
      if (phase0_ >= 1.0f) {
        phase0_ -= 1.0f;
      }
      phase1_ += f1;
      if (phase1_ >= 1.0f) {
        phase1_ -= 1.0f;
      }

      osc0_sub[s] = ReadZoneCrossfade(zp0, phase0_);
      osc1_sub[s] = ReadZoneCrossfade(zp1, phase1_);
    }

    // [0.25, 0.5, 0.25] decimation to the output rate: a null at 48 kHz for
    // the cost of -1.4 dB at 12 kHz and -6.0 dB at 24 kHz (SPEC R7), the same
    // tradeoff z-filter accepted for the same no-internal-oversampling
    // situation.
    const float osc0 =
        0.25f * osc0_decimator_ + 0.5f * osc0_sub[0] + 0.25f * osc0_sub[1];
    const float osc1 =
        0.25f * osc1_decimator_ + 0.5f * osc1_sub[0] + 0.25f * osc1_sub[1];
    osc0_decimator_ = osc0_sub[1];
    osc1_decimator_ = osc1_sub[1];

    if (stereo) {
      // Each ear gets one full voice of the detuned pair instead of the
      // mono sum's partial cancellation.
      out[i] = osc0;
      aux[i] = osc1;
    } else {
      // Braids' exact `*buffer >>= 1; *buffer += *temp_buffer >> 1;`
      // (macro_oscillator.cc:345-346). AUX is the complementary difference,
      // silent whenever the two voices are in unison.
      out[i] = 0.5f * (osc0 + osc1);
      aux[i] = 0.5f * (osc0 - osc1);
    }
  }
}

