// Braids' Interpolate824 read of a 257-entry table (256 points per cycle,
// entry 256 duplicating entry 0), continuous: `index` is 8 bits of integer
// position and a fraction, exactly as analog_oscillator.cc:585's Crossfade
// reads wave_1/wave_2. Normalized by the widest entry across all 15 zones,
// checked programmatically to be exactly 32767 (SPEC: never retype table
// numbers, so this bound is derived, not assumed) -- close enough to 32768
// that the +/-1 LSB gap is inaudible and the table stays safely inside
// +/-1.0.
inline float ReadZoneTable(const int16_t* table, float phase) {
  float index = phase * 256.0f;
  int integral = static_cast<int>(index);
  if (integral < 0) {
    integral = 0;
  } else if (integral > 255) {
    integral = 255;
  }
  const float fractional = index - static_cast<float>(integral);
  const float a = static_cast<float>(table[integral]);
  const float b = static_cast<float>(table[integral + 1]);
  return (a + (b - a) * fractional) * (1.0f / 32768.0f);
}

// analog_oscillator.cc:568-586, continuous: `zone_position` is shifted_pitch
// expressed in zones (8 semitones each) instead of 1/128-semitone integer
// units with a 10-bit fraction. Clamping the continuous position to
// [0, kBuzzNumZones - 1] before splitting it into an integer zone and a
// fractional blend reproduces Braids' two-stage index clamp exactly: at the
// top, blend lands on 1.0 and selects the last zone alone, the same result
// as Braids' wave_1 == wave_2 degeneracy; at the bottom (unreachable in real
// Braids, since shifted_pitch can't go negative, but reachable here through
// MORPH's new zone-spread axis) it saturates the same way at zone 0.
inline float ReadZoneCrossfade(float zone_position, float phase) {
  CONSTRAIN(zone_position, 0.0f, static_cast<float>(kBuzzNumZones - 1));
  int zone = static_cast<int>(zone_position);
  if (zone > kBuzzNumZones - 2) {
    zone = kBuzzNumZones - 2;
  }
  const float blend = zone_position - static_cast<float>(zone);
  const float a = ReadZoneTable(kBuzzZones[zone], phase);
  const float b = ReadZoneTable(kBuzzZones[zone + 1], phase);
  return a + (b - a) * blend;
}

