void WaveScanEngine::Init(BufferAllocator* allocator) {
  // Two mirrored 32-float decimator rings and a handful of integers; nothing
  // from the shared arena.
  (void) allocator;
  model_quantizer_.Init(WAVE_SCAN_MODEL_LAST, 0.05f, false);
  Reset();
}

void WaveScanEngine::Reset() {
  phase_ = 0.0f;
  frequency_ = 0.01f;
  // Braids' previous_parameter_ and smoothed_parameter_ are NOT cleared by
  // DigitalOscillator::Init() -- they are zero because the module's oscillator
  // is a file-scope object (braids.cc:59). So zero is the state the module
  // boots in, and it is the state this engine resets to: the bank knob adopts
  // its real value on the first block through the hysteresis, and WLIN's scan
  // ramps in from the bottom of the line over about 6 ms.
  bank_parameter_ = 0;
  scan_ = 0;
  previous_scan_ = 0;
  for (size_t i = 0; i < kWaveScanDecimatorStorageSize; ++i) {
    decimator_main_[i] = 0.0f;
    decimator_aux_[i] = 0.0f;
  }
  decimator_write_ = 0;
}

void WaveScanEngine::Render(
    const EngineParameters& parameters,
    float* out,
    float* aux,
    size_t size,
    bool* already_enveloped) {
  *already_enveloped = false;

  // Braids' Strike() only raises strike_ (digital_oscillator.h:284) and none
  // of these three render functions reads it, so a trigger leaves the phase
  // running on the module and does so here too.

  const int model = model_quantizer_.Process(parameters.harmonics);
  const bool stereo = PLAITS_STEREO_WAVE_SCAN && parameters.stereo;

  // 4x oversampling to reach Braids' 192 kHz internal rate, so the ceiling is
  // a quarter of Plaits' own (R4).
  float increment = NoteToFrequency(parameters.note) * 0.25f;
  if (increment > kWaveScanMaxIncrement) {
    increment = kWaveScanMaxIncrement;
  }

  const float snap = (parameters.macro - 0.5f) * 2.0f;
  const float spread = stereo ? kWaveScanStereoSpread : 0.0f;

  const int32_t p_timbre = Parameter(parameters.timbre);
  const int32_t p_color = Parameter(parameters.morph);

  ParameterInterpolator fm(&frequency_, increment, size);

  if (model == WAVE_SCAN_MODEL_WAVETABLES) {
    // digital_oscillator.cc:1531. The bank knob only moves when it moves by
    // more than 64 counts, so a slow sweep lags by up to that much.
    if (p_color > bank_parameter_ + kWaveScanBankHysteresis ||
        p_color < bank_parameter_ - kWaveScanBankHysteresis) {
      bank_parameter_ = p_color;
    }
    // :1536. 0..32767 * 20 >> 15 spans 0..19 exactly.
    uint32_t bank = static_cast<uint32_t>(bank_parameter_) * 20 >> 15;
    if (bank >= kWaveScanNumBanks) {
      bank = kWaveScanNumBanks - 1;
    }
    const WavetableDefinition& wt = kWavetableDefinitions[bank];

    // :1543. The top 16 bits select the pair out of the bank's index list and
    // the low 16 are the crossfade between them.
    const uint32_t wave_pointer =
        static_cast<uint32_t>(p_timbre << 1) * wt.num_steps;
    const uint8_t* wave_a =
        kWaves + (wt.wave_index[wave_pointer >> 16] << 7);
    const uint8_t* wave_b =
        kWaves + (wt.wave_index[(wave_pointer >> 16) + 1] << 7);
    const float position = SnapBalance(
        static_cast<float>(wave_pointer & 0xffff) * (1.0f / 65536.0f), snap);

    const float balance_main = Offset(position, -spread);
    const float balance_side = stereo
        ? Offset(position, spread)
        : 1.0f - position;

    for (size_t i = 0; i < size; ++i) {
      float step = fm.Next();
#if PLAITS_BUILD_FREQUENCY_OFFSET_FM
      if (parameters.frequency_offset) {
        step += parameters.frequency_offset[i] * 0.25f;
        CONSTRAIN(step, -kWaveScanMaxIncrement, kWaveScanMaxIncrement);
      }
#endif
      float main_accumulator = 0.0f;
      float side_accumulator = 0.0f;
      for (int j = 0; j < 4; ++j) {
        phase_ += step;
        if (phase_ >= 1.0f) {
          phase_ -= 1.0f;
        } else if (phase_ < 0.0f) {
          phase_ += 1.0f;
        }
        const float scaled = phase_ * 128.0f;
        int32_t index = static_cast<int32_t>(scaled);
        const float fraction = scaled - static_cast<float>(index);

        const float a = ReadWave(wave_a, index, fraction);
        const float b = ReadWave(wave_b, index, fraction);
        main_accumulator += Blend(a, b, balance_main);
        side_accumulator += Blend(a, b, balance_side);
        if (j & 1) {
          // Braids' `>> 1` box average of each oversampled pair (:1558-1560).
          Push(main_accumulator * 0.5f, side_accumulator * 0.5f);
          main_accumulator = 0.0f;
          side_accumulator = 0.0f;
        }
      }
      out[i] = Decimate(decimator_main_, decimator_write_);
      aux[i] = Decimate(decimator_aux_, decimator_write_);
    }
  } else if (model == WAVE_SCAN_MODEL_MAP) {
    // :1575-1580. `parameter * 15 >> 4` tops out at 30719, so the module's
    // uint16_t store never truncates; `>> 11` is the cell and the low 11 bits
    // are the position inside it (`p << 5` in uint16 is (p mod 2048) * 32).
    const int32_t px = (p_timbre * kWaveScanMapCells) >> 4;
    const int32_t py = (p_color * kWaveScanMapCells) >> 4;
    const int32_t cell_x = px >> 11;
    const int32_t cell_y = py >> 11;
    const float x = SnapBalance(
        static_cast<float>(px & 2047) * (1.0f / 2048.0f), snap);
    const float y = SnapBalance(
        static_cast<float>(py & 2047) * (1.0f / 2048.0f), snap);

    // :1584-1589. X selects the row, Y the column.
    const uint8_t* wave_00 =
        kWaves + (kWaveMap[cell_x * 16 + cell_y] << 7);
    const uint8_t* wave_01 =
        kWaves + (kWaveMap[cell_x * 16 + cell_y + 1] << 7);
    const uint8_t* wave_10 =
        kWaves + (kWaveMap[(cell_x + 1) * 16 + cell_y] << 7);
    const uint8_t* wave_11 =
        kWaves + (kWaveMap[(cell_x + 1) * 16 + cell_y + 1] << 7);

    // The inner Crossfade runs on Y (:1602-1603), the outer Mix on X (:1604).
    // AUX takes the opposite corner of the cell in mono; in stereo the two
    // sides keep one Y and pull apart on X, so they stay one sound.
    const float y_main = y;
    const float y_side = stereo ? y : 1.0f - y;
    const float x_main = Offset(x, -spread);
    const float x_side = stereo ? Offset(x, spread) : 1.0f - x;

    for (size_t i = 0; i < size; ++i) {
      float step = fm.Next();
#if PLAITS_BUILD_FREQUENCY_OFFSET_FM
      if (parameters.frequency_offset) {
        step += parameters.frequency_offset[i] * 0.25f;
        CONSTRAIN(step, -kWaveScanMaxIncrement, kWaveScanMaxIncrement);
      }
#endif
      float main_accumulator = 0.0f;
      float side_accumulator = 0.0f;
      for (int j = 0; j < 4; ++j) {
        phase_ += step;
        if (phase_ >= 1.0f) {
          phase_ -= 1.0f;
        } else if (phase_ < 0.0f) {
          phase_ += 1.0f;
        }
        const float scaled = phase_ * 128.0f;
        int32_t index = static_cast<int32_t>(scaled);
        const float fraction = scaled - static_cast<float>(index);

        const float r00 = ReadWave(wave_00, index, fraction);
        const float r01 = ReadWave(wave_01, index, fraction);
        const float r10 = ReadWave(wave_10, index, fraction);
        const float r11 = ReadWave(wave_11, index, fraction);

        main_accumulator += Blend(
            Blend(r00, r01, y_main), Blend(r10, r11, y_main), x_main);
        side_accumulator += Blend(
            Blend(r00, r01, y_side), Blend(r10, r11, y_side), x_side);
        if (j & 1) {
          Push(main_accumulator * 0.5f, side_accumulator * 0.5f);
          main_accumulator = 0.0f;
          side_accumulator = 0.0f;
        }
      }
      out[i] = Decimate(decimator_main_, decimator_write_);
      aux[i] = Decimate(decimator_aux_, decimator_write_);
    }
  } else {
    // :1632. One block of the module's own one-pole, integer shift included:
    // Plaits' 12-sample block at 48 kHz and Braids' 24 at 96 kHz are both
    // 4000 blocks per second, so the coefficient transfers unchanged.
    const int32_t previous = previous_scan_;
    scan_ = (3 * scan_ + (p_timbre << 1)) >> 2;
    previous_scan_ = scan_;

    // :1635-1637. wave_0 is the PREVIOUS block's position -- Braids stores it
    // as previous_parameter_[0] = smoothed >> 1 at :1730 and reads it back
    // with >> 9, which is the same index as this block's >> 10.
    int32_t index_0 = previous >> 10;
    int32_t index_1 = scan_ >> 10;
    CONSTRAIN(index_0, 0, kWaveScanLineLast);
    CONSTRAIN(index_1, 0, kWaveScanLineLast);
    // Braids indexes one past the scan position, which runs off the end of a
    // 64-entry table above TIMBRE 0.9844. Clamped here; declared in the
    // header, and tests/ab.json stops at 0.98.
    int32_t index_2 = index_1 + 1;
    CONSTRAIN(index_2, 0, kWaveScanLineLast);

    const uint8_t* wave_0 = kWaves + (kWaveLine[index_0] << 7);
    const uint8_t* wave_1 = kWaves + (kWaveLine[index_1] << 7);
    const uint8_t* wave_2 = kWaves + (kWaveLine[index_2] << 7);

    // :1639. The low 10 bits of the scan, as a crossfade.
    const float smooth_xfade = SnapBalance(
        static_cast<float>(scan_ & 1023) * (1.0f / 1024.0f), snap);

    // :1642. `parameter_[1] << 3` reaches 262136 and is handed to a uint16_t
    // argument, so COLOR is four zones of a full 0..1 sweep and the zone
    // decides what is being mixed.
    const int32_t balance_raw = p_color << 3;
    const int32_t zone = balance_raw >> 16;
    const float balance = static_cast<float>(balance_raw & 0xffff) *
        (1.0f / 65536.0f);
    const float balance_main = Offset(balance, -spread);
    const float balance_side = stereo
        ? Offset(balance, spread)
        : 1.0f - balance;

    // :1641. Braids advances this once per 192 kHz sub-sample and there are
    // two of them per output sample; the port has four, so each step is half
    // as large and the ramp still spans exactly one block.
    float rough_xfade = 0.0f;
    const float rough_increment = size
        ? static_cast<float>(32768 / static_cast<int32_t>(size)) *
              (1.0f / 65536.0f) * 0.5f
        : 0.0f;

    for (size_t i = 0; i < size; ++i) {
      float step = fm.Next();
#if PLAITS_BUILD_FREQUENCY_OFFSET_FM
      if (parameters.frequency_offset) {
        step += parameters.frequency_offset[i] * 0.25f;
        CONSTRAIN(step, -kWaveScanMaxIncrement, kWaveScanMaxIncrement);
      }
#endif
      float main_accumulator = 0.0f;
      float side_accumulator = 0.0f;
      for (int j = 0; j < 4; ++j) {
        const float scaled = phase_ * 128.0f;
        int32_t index = static_cast<int32_t>(scaled);
        const float fraction = scaled - static_cast<float>(index);
        const int32_t index_64 = index & ~1;
        const int32_t index_16 = index & ~7;

        float first = 0.0f;
        float second = 0.0f;
        if (zone == 0) {
          // :1656-1666. 64-step sample-and-hold against the interpolated
          // read, both on the de-zipper pair.
          first = Blend(ReadWaveStep(wave_0, index_64),
                        ReadWaveStep(wave_1, index_64), rough_xfade);
          second = Blend(ReadWave(wave_0, index, fraction),
                         ReadWave(wave_1, index, fraction), rough_xfade);
        } else if (zone == 1) {
          // :1677-1687. The de-zipper pair against the scanned pair.
          first = Blend(ReadWave(wave_0, index, fraction),
                        ReadWave(wave_1, index, fraction), rough_xfade);
          second = Blend(ReadWave(wave_1, index, fraction),
                         ReadWave(wave_2, index, fraction), smooth_xfade);
        } else if (zone == 2) {
          // :1698-1707. The scanned pair, interpolated against 64-step.
          first = Blend(ReadWave(wave_1, index, fraction),
                        ReadWave(wave_2, index, fraction), smooth_xfade);
          second = Blend(ReadWaveStep(wave_1, index_64),
                         ReadWaveStep(wave_2, index_64), smooth_xfade);
        } else {
          // :1716-1725. 64-step against 16-step.
          first = Blend(ReadWaveStep(wave_1, index_64),
                        ReadWaveStep(wave_2, index_64), smooth_xfade);
          second = Blend(ReadWaveStep(wave_1, index_16),
                         ReadWaveStep(wave_2, index_16), smooth_xfade);
        }

        main_accumulator += Blend(first, second, balance_main);
        side_accumulator += Blend(first, second, balance_side);
        if (j & 1) {
          Push(main_accumulator * 0.5f, side_accumulator * 0.5f);
          main_accumulator = 0.0f;
          side_accumulator = 0.0f;
        }

        // Braids advances the phase and the de-zipper AFTER the read
        // (:1656-1666), so the block opens on the previous block's wave.
        phase_ += step;
        if (phase_ >= 1.0f) {
          phase_ -= 1.0f;
        } else if (phase_ < 0.0f) {
          phase_ += 1.0f;
        }
        rough_xfade += rough_increment;
      }
      out[i] = Decimate(decimator_main_, decimator_write_);
      aux[i] = Decimate(decimator_aux_, decimator_write_);
    }
  }
}

