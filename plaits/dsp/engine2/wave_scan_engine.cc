// Braids works in 15-bit knob counts, and every index this engine derives is
// an integer shift of one, so the knob is taken into those counts first --
// exactly as the reference renderer's ToParameter does on the other side.
inline int32_t Parameter(float macro) {
  int32_t value = static_cast<int32_t>(macro * 32767.0f);
  CONSTRAIN(value, 0, 32767);
  return value;
}

// stmlib::Interpolate824 on a uint8_t table, which is how all three models
// read a wave: `(a << 8) + ((b - a) * fraction >> 16) - 32768` over bytes
// centred on 128 (stmlib/utils/dsp.h). In normalized form that is exactly
// (a + (b - a) * fraction) / 128 - 1, spanning -1.0 to +255/128 - 1.
//
// The 8-bit source quantisation is the whole character of these models and is
// reproduced by carrying Braids' own bytes; what is NOT reproduced is the
// >> 16 truncation of the interpolation term, which loses at most one count of
// the +/-32768 range this returns, before the port box-averages four of them.
inline float ReadWave(const uint8_t* wave, int32_t index, float fraction) {
  const float a = static_cast<float>(wave[index]);
  const float b = static_cast<float>(
      wave[static_cast<uint32_t>(index + 1) & kWaveScanWaveMask]);
  return (a + (b - a) * fraction) * (1.0f / 128.0f) - 1.0f;
}

// The same read with the interpolation switched off, which is what WLIN's
// phase masks produce: `(phase >> 1) & 0xfe000000` and `& 0xf8000000` clear
// every fraction bit as well as the low bits of the index, so the wave is
// held between steps rather than interpolated across them.
inline float ReadWaveStep(const uint8_t* wave, int32_t index) {
  return static_cast<float>(wave[index]) * (1.0f / 128.0f) - 1.0f;
}

// stmlib::Crossfade over a pair of waves at one phase, and the Mix that takes
// two already-crossfaded values. Braids' balances are uint16 over 65536 and
// its Mix spells the complement `65535 - balance`, so its "full" crossfade is
// 65535/65536; these are unity. -0.00013 dB, and it is declared.
inline float Blend(float a, float b, float balance) {
  return a + (b - a) * balance;
}

// MACRO. `snap` is (macro - 0.5) * 2, so zero at the detent and the balance
// passes through untouched -- which is what makes every A/B case comparable.
// Positive pulls the scan crossfade to whichever end it is nearer, so the scan
// steps between whole waves; negative pulls it to 0.5, so neighbouring waves
// sum instead of trading.
inline float SnapBalance(float balance, float snap) {
  if (snap > 0.0f) {
    const float target = balance < 0.5f ? 0.0f : 1.0f;
    return balance + (target - balance) * snap;
  }
  if (snap < 0.0f) {
    return balance + (0.5f - balance) * (-snap);
  }
  return balance;
}

inline float Offset(float balance, float amount) {
  float value = balance + amount;
  CONSTRAIN(value, 0.0f, 1.0f);
  return value;
}

// The 19-tap Hamming halfband that takes the 96 kHz stream Braids itself ends
// at down to the output rate. Only the centre and the odd offsets are
// non-zero, so it is six multiplies. Re-derived here from the windowed-sinc
// definition (fc = 0.25, Hamming, 19 taps, normalized to unity DC gain) and
// agreeing with these printed constants to 2.4e-09. Against the 127-tap
// Blackman-Harris halfband the A/B harness decimates the Braids reference with
// (braids/test/render_braids_model.cc, Decimate2x) it is within 0.13 dB to
// 16 kHz, -1.41 dB at 20 kHz and -3.15 dB at 22 kHz, with a worst-case alias
// residue of -10.4 dB at 26 kHz falling to -38.4 dB by 32 kHz.
inline float Decimate(const float* buffer, uint32_t write) {
  const float* newest = buffer + kWaveScanDecimatorSize
      + ((write - 1u) & kWaveScanDecimatorMask);
#define WS_TAP(j) newest[-(j)]
  return 0.49863366f * WS_TAP(9)
      + 0.30863382f * (WS_TAP(8) + WS_TAP(10))
      - 0.08147628f * (WS_TAP(6) + WS_TAP(12))
      + 0.02921222f * (WS_TAP(4) + WS_TAP(14))
      - 0.00850828f * (WS_TAP(2) + WS_TAP(16))
      + 0.00282169f * (WS_TAP(0) + WS_TAP(18));
#undef WS_TAP
}

